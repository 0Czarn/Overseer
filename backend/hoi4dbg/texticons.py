"""Text icons of the Descriptive Icons mod (Steam workshop 3797575405, over its base mod Modifier Icons, 2668048070)
bundled with the app.

The mods put an icon in front of the game's texts: their localisation replaces e.g.
    MODIFIER_INDUSTRY_REPAIR_FACTOR: "£factory_repair_speed_modifier_texticon  Factory Repair Speed"
and their interface/*.gfx name the texture of each icon (GFX_<name> -> gfx/texticons/.../<name>.dds).
`build` turns that into PNG files under app/renderer/assets/texticons and a module app/renderer/lib/texticons.js:
    TEXT_ICONS = {modifier or localisation key (lower case, without MODIFIER_): "<name>.png"}
so the app shows the icons without the mods being installed. Run again after a mod update:
    python -m hoi4dbg.texticons "<Hearts of Iron IV installation>" "<workshop>/394360/2668048070" "<.../3797575405>"
(later mods override earlier ones, as in the game's load order)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from . import gfx

LOC_LINE = re.compile(r'^\s*([A-Za-z0-9_.\-]+):\d*\s*"(.*)"\s*$')
ICON_REF = re.compile(r"£([A-Za-z0-9_]+)")
SPRITE = re.compile(r'name\s*=\s*"?GFX_([A-Za-z0-9_]+)"?\s*texturefile\s*=\s*"([^"]+)"', re.I)
MAX_SIDE = 64


def icon_keys(mod: Path) -> dict[str, str]:
    """{key: icon name} from the mod's English localisation: the first £icon of each text. Keys lower case, MODIFIER_
    dropped (the app's modifier keys), the plain localisation key kept too."""
    out: dict[str, str] = {}
    for path in sorted((mod / "localisation").rglob("*_l_english.yml")):
        for line in path.read_text(encoding="utf-8-sig", errors="replace").splitlines():
            m = LOC_LINE.match(line)
            ref = ICON_REF.search(m.group(2)) if m else None
            if not ref:
                continue
            key = m.group(1).lower()
            out[key] = ref.group(1)
            if key.startswith("modifier_"):
                out[key[len("modifier_"):]] = ref.group(1)
    return out


def textures(mod: Path) -> dict[str, Path]:
    """{icon name: texture} from the mod's interface/*.gfx (existing files only)."""
    out: dict[str, Path] = {}
    for path in sorted((mod / "interface").glob("*.gfx")):
        for name, texture in SPRITE.findall(path.read_text(encoding="utf-8-sig", errors="replace")):
            path = mod / texture.replace("\\", "/")
            if path.exists():   # Modifier Icons names some textures it does not ship: the game's own stay
                out[name] = path
    return out


def build(mods: list[Path], assets: Path, module: Path, game: Path | None = None) -> dict[str, int]:
    """Writes the PNG icons and the key -> icon module; returns counts. Later mods override earlier ones; icons the
    mods use from the game itself are taken from `game` (the installation)."""
    keys: dict[str, str] = {}
    tex: dict[str, Path] = {}
    if game is not None:
        tex.update((name[4:], Path(texture)) for name, texture in gfx.sprites((str(game),)).items()
                   if name.startswith("GFX_"))
    for mod in mods:
        keys.update(icon_keys(mod))
        tex.update(textures(mod))
    assets.mkdir(parents=True, exist_ok=True)
    written: set[str] = set()
    failed = 0
    for name in sorted(set(keys.values())):
        path = tex.get(name)
        decoded = gfx._dds_rgba(path.read_bytes(), MAX_SIDE) if path and path.exists() else None
        if not decoded:
            failed += 1
            continue
        (assets / f"{name}.png").write_bytes(gfx._png(*decoded))
        written.add(name)
    mapping = {k: f"{v}.png" for k, v in sorted(keys.items()) if v in written}
    module.write_text("// Generated by hoi4dbg/texticons.py (backend) from the mods Modifier Icons (Steam workshop 2668048070)\n"
                      "// and Descriptive Icons (3797575405). {modifier / localisation key (lower case): icon file in\n"
                      "// assets/texticons}\n"
                      f"export const TEXT_ICONS = {json.dumps(mapping, indent=0, sort_keys=True)};\n", encoding="utf-8")
    return {"keys": len(mapping), "icons": len(written), "missing": failed}


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2]
    print(build([Path(a) for a in sys.argv[2:]], root / "app/renderer/assets/texticons",
                root / "app/renderer/lib/texticons.js", Path(sys.argv[1])))
